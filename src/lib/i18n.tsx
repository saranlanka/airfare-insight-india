const DICTS: Record<LangCode, Partial<Record<TKey, string>>> = {
  en,
  hi,
  te,
  ta: {},
  bn: {},
  mr: {},
  kn: {},
  gu: {},
};

const STORAGE_KEY = "afii.lang";

type I18nValue = {
  lang: LangCode;
  setLang: (l: LangCode) => void;
  t: (key: TKey) => string;
  isFull: boolean;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("en");

  useEffect(() => {
    try {
      const stored = localStorage.getItem(STORAGE_KEY) as LangCode | null;
      if (stored && LANGUAGES.some((l) => l.code === stored)) setLangState(stored);
    } catch {
      /* storage unavailable — stay on English */
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l: LangCode) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
  }, []);

  const value = useMemo<I18nValue>(() => {
    const dict = DICTS[lang];
    return {
      lang,
      setLang,
      isFull: LANGUAGES.find((l) => l.code === lang)?.full ?? false,
      t: (key: TKey) => dict[key] ?? en[key] ?? String(key),
    };
  }, [lang, setLang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
